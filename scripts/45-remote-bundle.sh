#!/usr/bin/env bash
# For a lab running on a server: write .state/remote/, everything another
# machine on the LAN needs to use the cluster through this host over SSH.
#
#   kubeconfig   API server via an SSH tunnel on localhost:6443
#   ssh_config   "rke2-lab" (the tunnel) + cp1/worker1/worker2 via ProxyJump
#   ssh_key      the lab's VM key
#
# The VMs stay on the private libvirt network; nothing on this host is opened
# beyond its existing SSH server.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "${SCRIPT_DIR}/lib.sh"

KCONF="${STATE_DIR}/kubeconfig"
[[ -f "${KCONF}" ]] || die "kubeconfig missing — run 'make kubeconfig'"
HOST="${REMOTE_HOST:-$(host_lan_ip)}"
[[ -n "${HOST}" ]] || die "Couldn't detect this host's LAN IP — set REMOTE_HOST in config.env"
USER_NAME="$(id -un)"
CP_IP="$(control_plane_ip)"
OUT="${STATE_DIR}/remote"
DEST='~/.rke2-lab'           # where the files live on the other machine

mkdir -p "${OUT}" && chmod 700 "${OUT}"

# kubeconfig: through the tunnel. RKE2's serving cert already covers 127.0.0.1.
# Rename RKE2's "default" cluster/user/context so it merges with other configs.
sed -e "s|server: https://${CP_IP//./\\.}:6443|server: https://127.0.0.1:6443|" \
    -e 's|^\([ -]*\)name: default$|\1name: rke2-lab|' \
    -e 's|^\([ -]*\)cluster: default$|\1cluster: rke2-lab|' \
    -e 's|^\([ -]*\)user: default$|\1user: rke2-lab|' \
    -e 's|^current-context: default$|current-context: rke2-lab|' \
    "${KCONF}" > "${OUT}/kubeconfig"
chmod 600 "${OUT}/kubeconfig"

install -m 600 "${SSH_KEY}" "${OUT}/ssh_key"

{
  echo "# instant-rke2-lab on ${HOST} — generated by 'make remote-bundle'."
  echo "# Use with: ssh -F ${DEST}/ssh_config <host>"
  echo
  echo "Host rke2-lab"
  echo "  HostName ${HOST}"
  echo "  User ${USER_NAME}"
  echo "  # kubectl on this machine -> API server on ${CP_IP}"
  echo "  LocalForward 6443 ${CP_IP}:6443"
  echo "  ExitOnForwardFailure yes"
  echo "  ServerAliveInterval 30"
  echo
  NAMES=()
  for entry in "${VM_LIST[@]}"; do read -r name _ _ _ _ _ <<<"$entry"; NAMES+=("$name"); done
  echo "Host ${NAMES[*]}"
  echo "  ProxyJump rke2-lab"
  echo "  User ${SSH_USER}"
  echo "  IdentityFile ${DEST}/ssh_key"
  echo "  StrictHostKeyChecking no"
  echo "  UserKnownHostsFile /dev/null"
  echo "  LogLevel ERROR"
  for entry in "${VM_LIST[@]}"; do
    read -r name _ _ _ ip _ <<<"$entry"
    echo
    echo "Host ${name}"
    echo "  HostName ${ip}"
  done
} > "${OUT}/ssh_config"
chmod 600 "${OUT}/ssh_config"

ok "Wrote ${OUT}/ (kubeconfig, ssh_config, ssh_key)"
cat <<EOF

── On the other machine ────────────────────────────────────────────────
  # copy the bundle (once, and again after a rebuild)
  mkdir -p ${DEST} && chmod 700 ${DEST}
  scp '${USER_NAME}@${HOST}:${OUT}/*' ${DEST}/

  # open the API tunnel in the background
  ssh -F ${DEST}/ssh_config -fN rke2-lab

  export KUBECONFIG=${DEST}/kubeconfig
  kubectl get nodes

  # shell on a node (jumps through ${HOST})
  ssh -F ${DEST}/ssh_config ${NAMES[0]}

  # Kubeflow UI from there, through the same tunnel
  kubectl -n istio-system port-forward svc/istio-ingressgateway 8080:80
────────────────────────────────────────────────────────────────────────
EOF
